#!/usr/bin/env node
/**
 * Generates docs/CONFIGURATION.md from the configuration schemas in
 * src/core/env-config.ts and src/core/operator-config.ts.
 *
 *   node scripts/gen-config-docs.mjs          rewrite the file when it changed
 *   node scripts/gen-config-docs.mjs --check  write nothing; exit 1 when it is stale
 *
 * The schemas are loaded from source through tsx, so no build is needed, and
 * the output goes through Prettier so the committed file is already formatted.
 * The output depends only on the schemas: no dates, no host paths.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { tsImport } from 'tsx/esm/api';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs', 'CONFIGURATION.md');
const check = process.argv.includes('--check');

const env = await tsImport('../src/core/env-config.ts', import.meta.url);
const operator = await tsImport('../src/core/operator-config.ts', import.meta.url);

const code = text => `\`${text}\``;

// Table cells cannot contain raw pipes or line breaks.
const cell = text =>
  String(text)
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ');

function table(header, rows) {
  const line = cells => `| ${cells.map(cell).join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n');
}

function typeLabel(variable) {
  if (variable.kind === 'enum') return variable.values.map(code).join(', ');
  if (variable.values) return `${variable.kind} of ${variable.values.map(code).join(', ')}`;
  return variable.kind;
}

// Schema text is already Markdown; plain default values are shown as code.
function defaultLabel(variable) {
  if (variable.defaultText) return variable.defaultText;
  return variable.defaultValue === undefined ? 'unset' : code(variable.defaultValue);
}

function describeVariable(variable) {
  const aliases = variable.aliases.length
    ? ` Deprecated names: ${variable.aliases.map(alias => code(alias.name)).join(', ')}.`
    : '';
  return `${variable.description}${aliases}`;
}

function render() {
  const variables = env.describeEnvVars();
  const current = variables.filter(variable => !variable.deprecated);
  const retired = variables.filter(variable => variable.deprecated);
  const out = [];

  out.push('# Configuration');
  out.push(
    '<!-- Generated by scripts/gen-config-docs.mjs from src/core/env-config.ts and src/core/operator-config.ts. Do not edit by hand: change the schema and run `npm run gen:config-docs`. -->'
  );
  out.push(
    'ahk-mcp is configured by whoever launches it: environment variables (usually the `env` block of the MCP client entry) and an optional `operator-config.json` file. Neither can be changed by a tool call, so a model cannot widen its own sandbox, swap the AutoHotkey executable or re-enable tools the operator turned off.'
  );

  out.push('## Value formats');
  out.push(
    [
      '- **Booleans** accept `1`, `true`, `yes`, `on` and `0`, `false`, `no`, `off`, in any letter case.',
      '- **Empty values** count as unset.',
      '- **Directory lists** are separated by `;`. On Linux and macOS, `:` works too.',
      '- **Other lists** are separated by commas.',
      '- **Invalid values** produce a warning on stderr, and the default is used instead. Two settings fail closed: an unrecognized `AHK_MCP_READ_ONLY` turns read-only mode on, and `AHK_MCP_TOOLSETS` keeps only the toolset names it recognizes.',
      '- **Unknown `AHK_MCP_*` variables** are reported once on stderr, with a suggestion when the name is close to a known one.',
      '- **Deprecated names** still work and are reported once on stderr. They are listed [at the end](#deprecated-names). When both a deprecated name and its replacement are set, the replacement wins.',
    ].join('\n')
  );

  out.push('## Precedence');
  out.push(
    [
      '1. The environment variable.',
      '2. A deprecated alias of it.',
      '3. `operator-config.json`, for the AutoHotkey, fork and thqby paths, toolsets and file extensions.',
      '4. The built-in default, or discovery for executables.',
    ].join('\n')
  );
  out.push(
    'Allowed directories are combined rather than overridden: the client roots, `AHK_MCP_ALLOWED_DIRS`, `AHK_MCP_SCRIPT_DIR`, `allowedDirs` from the file, and the working directory unless it is a drive root, the home directory or a system directory.'
  );

  out.push('## Environment variables');
  for (const group of env.ENV_VAR_GROUPS) {
    const rows = current.filter(variable => variable.group === group.id);
    if (rows.length === 0) continue;
    out.push(`### ${group.title}`);
    out.push(group.intro);
    out.push(
      table(
        ['Variable', 'Type', 'Default', 'Description'],
        rows.map(variable => [
          code(variable.name),
          typeLabel(variable),
          defaultLabel(variable),
          describeVariable(variable),
        ])
      )
    );
  }

  out.push('## operator-config.json');
  out.push(
    `The file is ${code(operator.OPERATOR_CONFIG_FILENAME)} in the directory named by ${code('AHK_MCP_CONFIG_DIR')}, which defaults to ${code('%APPDATA%\\ahk-mcp')} on Windows and ${code('~/.config/ahk-mcp')} elsewhere. It is optional and every key is optional.`
  );
  out.push(
    [
      '- The server only reads it. It is re-read when its modification time or size changes, so edits apply without a restart. Toolsets are the exception: they are evaluated at startup.',
      "- Relative paths are resolved against the file's own directory.",
      '- A UTF-8 byte order mark is accepted. Unknown keys are reported as warnings and ignored.',
      '- Each key is checked on its own. An invalid list entry is dropped and the rest of the list is used; any other invalid value is ignored, as if the key were absent. `toolsets` fails closed: it keeps only the names it recognizes, and a value that is not a list lists no toolsets.',
      '- If the file cannot be read or is not a valid JSON object, none of it is used. No toolsets are listed then, unless `AHK_MCP_TOOLSETS` is set; the other settings fall back as if the file were absent. Remember to double backslashes in Windows paths.',
      '- Every value that is not used is reported on stderr as an error, which no log level hides.',
    ].join('\n')
  );
  out.push(
    table(
      ['Key', 'Type', 'Description'],
      operator
        .describeOperatorConfig()
        .map(entry => [code(entry.key), entry.kind, entry.description])
    )
  );
  out.push('Example:');
  out.push(
    [
      '```json',
      JSON.stringify(
        {
          allowedDirs: ['C:\\Scripts', 'D:\\Shared\\AHK'],
          ahkPath: 'C:\\Program Files\\AutoHotkey\\v2\\AutoHotkey64.exe',
          toolsets: ['files', 'analysis', 'docs', 'server'],
          fileExtensions: ['.ahk', '.ah2', '.ini'],
        },
        null,
        2
      ),
      '```',
    ].join('\n')
  );

  out.push('## Deprecated names');
  out.push(
    'Each of these produces a one-time warning on stderr. An alias still sets its replacement. A name without a replacement only affects 2.x code and goes away in 3.0.'
  );
  const aliasRows = current.flatMap(variable =>
    variable.aliases.map(alias => ({
      name: alias.name,
      cells: [code(alias.name), code(variable.name), alias.note ?? 'Same value.'],
    }))
  );
  const retiredRows = retired.map(variable => ({
    name: variable.name,
    cells: [code(variable.name), 'none', `${variable.description} ${variable.deprecated}`],
  }));
  // Code-unit order, so the output never depends on the host's locale.
  const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  out.push(
    table(
      ['Name', 'Replacement', 'Notes'],
      [...aliasRows, ...retiredRows].sort(byName).map(row => row.cells)
    )
  );

  return `${out.join('\n\n')}\n`;
}

const options = { ...(await prettier.resolveConfig(target)), filepath: target, endOfLine: 'lf' };
const generated = await prettier.format(render(), options);

let existing = null;
try {
  existing = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

if (check) {
  if (existing !== generated) {
    console.error(
      `${path.relative(root, target)} is out of date. Run \`npm run gen:config-docs\` and commit the result.`
    );
    process.exit(1);
  }
  console.log(`${path.relative(root, target)} is up to date.`);
} else if (existing === generated) {
  console.log(`${path.relative(root, target)} is already up to date.`);
} else {
  await writeFile(target, generated, 'utf8');
  console.log(`Wrote ${path.relative(root, target)}.`);
}
